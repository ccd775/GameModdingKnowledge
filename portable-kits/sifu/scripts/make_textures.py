# Sifu textures + UE build config for an atlas profile (plain python with PIL/numpy, after bake_ao.py page mode).
# python make_textures.py <profile> <work_dir> <remote_work_dir> [--flat-dir <dir>]
#   <work_dir>/ao/AO_<page>.png (bake_ao.py)  ->  <work_dir>/tex/T_*.png and <work_dir>/ue_build.json
#   <remote_work_dir>: the folder on the UE machine the files are copied to (ue_build.json lists paths there).
#   Atlas pages are read from the profile's tex_dir (under SIFU_MODELS_DIR, see profiles.py).
# BaseColor: the atlas colour page at 2048, alpha 255 on skin (face/body), 0 on cloth and hair (W-like).
# ComboMap: R roughness, G metal 0, B baked AO, A 230 skin / 255 cloth (same constants as the Karin_Original build).
import argparse
import json
import os
import sys
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "blender"))   # profiles.py (no bpy)
import profiles

# kind -> (roughness 0-255, ComboMap alpha, AO strength, UE parent, alpha of the BaseColor)
KIND = {"face": (140, 230, 0.6, "w_head", 255), "skin": (150, 230, 0.8, "w_body", 255),
        "hair": (115, 255, 0.9, "w_cloth", 0), "cloth": (205, 255, 1.0, "w_cloth", 0)}
FACE_PARAMS = {"textures": {"Aging_Mask": "T_Karin_Black", "Aging_Normal_A": "T_Karin_Flat_N", "Aging_Normal_B": "T_Karin_Flat_N"},
               "vectors": {"SSS_Color": [0.198, 0.0247, 0.0247, 1.0], "Hair_Dark": [0.0, 0.0, 0.0, 1.0], "Hair_Light": [1.0, 1.0, 1.0, 1.0]},
               "scalars": {"Camera Dist Falloff": 70.0}}
SKIN_PARAMS = {"textures": {"Aging_Mask": "T_Karin_Black", "Aging_Normal_A": "T_Karin_Flat_N", "Aging_Normal_B": "T_Karin_Flat_N"},
               "vectors": {"SSS_Color": [0.114, 0.0009, 0.0044, 1.0]}, "scalars": {"Camera Dist Falloff": 70.0}}
CLOTH_PARAMS = {"Normal": "T_Karin_Flat_N", "scalars": {"Camera Dist Falloff": 70.0}}
# T_Karin_Flat_N.png / T_Karin_Black.png: a flat normal and a black mask (RGB, size, colour). Generated by default (the
# bytes equal the Karin_Original build's files); --flat-dir copies existing files instead.
FLAT_SPEC = {"T_Karin_Flat_N": ((64, 64), (128, 128, 255)), "T_Karin_Black": ((16, 16), (0, 0, 0))}


def main(name, work, remote, flat=None):
    P = profiles.activate(name)
    tex_out = os.path.join(work, "tex")
    os.makedirs(tex_out, exist_ok=True)
    tid = P["asset_dir"].replace("Karin_", "")
    textures, materials = {}, {}
    for t in ("T_Karin_Flat_N", "T_Karin_Black"):
        if flat:
            Image.open(f"{flat}/{t}.png").save(f"{tex_out}/{t}.png")
        else:
            size, colour = FLAT_SPEC[t]
            Image.new("RGB", size, colour).save(f"{tex_out}/{t}.png")
        textures[t] = [f"{remote}/tex/{t}.png", "normal" if t.endswith("_N") else "mask"]
    for slot, spec in P["slots"].items():
        page, kind = spec["page"], spec["kind"]
        rough, calpha, strength, parent, balpha = KIND[kind]
        pg = page.replace("-", "_")
        cname = f"T_{tid}_{pg}_C" + ("S" if balpha == 255 else "")
        if cname not in textures:
            im = Image.open(P["tex_dir"] + "/" + P["tex_files"]["color"].format(page=page)).convert("RGBA")
            im = im.resize((2048, 2048), Image.LANCZOS)
            a = np.asarray(im).copy()
            a[..., 3] = balpha
            Image.fromarray(a, "RGBA").save(f"{tex_out}/{cname}.png")
            textures[cname] = [f"{remote}/tex/{cname}.png", "color"]
        sname = f"T_{tid}_{pg}_S_{kind}"
        if sname not in textures:
            ao = np.asarray(Image.open(f"{work}/ao/AO_{page}.png").convert("L"), np.float32) / 255.0
            ao = np.clip(1.0 - strength * (1.0 - ao), 0, 1) ** 0.8
            s = np.zeros(ao.shape + (4,), np.uint8)
            s[..., 0] = rough
            s[..., 2] = np.round(ao * 255).astype(np.uint8)
            s[..., 3] = calpha
            Image.fromarray(s, "RGBA").save(f"{tex_out}/{sname}.png")
            textures[sname] = [f"{remote}/tex/{sname}.png", "mask"]
        m = {"parent": parent, "BaseColor": cname, "ComboMap": sname}
        extra = FACE_PARAMS if kind == "face" else (SKIN_PARAMS if kind == "skin" else CLOTH_PARAMS)
        m.update(json.loads(json.dumps(extra)))
        if kind in ("face", "skin"):
            m["textures"]["Color_Old"] = cname
        materials[slot] = m
    for slot in P.get("same_as", {}):
        materials[slot] = {"same_as": P["same_as"][slot]}
    cfg = {"fbx": f"{remote}/SK_W_MainChar_01.fbx", "out_json": f"{remote}/ue_build_out.json", "asset_dir": P["asset_dir"],
           "textures": textures, "materials": materials, "cloth_json": f"{remote}/cloth.json"}
    json.dump(cfg, open(f"{work}/ue_build.json", "w", encoding="utf-8"), indent=1)
    print("TEXTURES_DONE", len(textures), "textures,", len(materials), "materials")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Sifu BaseColor / ComboMap PNGs and ue_build.json for an atlas profile "
                                             "(after bake_ao.py page mode).")
    ap.add_argument("profile", help="profile name in profiles.py (atlas profiles: opt, pt, umb, y)")
    ap.add_argument("work_dir", help="local build folder with ao/AO_<page>.png; tex/ and ue_build.json are written here")
    ap.add_argument("remote_work_dir", help="folder on the UE machine that receives the files (paths in ue_build.json)")
    ap.add_argument("--flat-dir", help="copy T_Karin_Flat_N.png / T_Karin_Black.png from here instead of generating them")
    a = ap.parse_args()
    main(a.profile, a.work_dir, a.remote_work_dir, a.flat_dir)
